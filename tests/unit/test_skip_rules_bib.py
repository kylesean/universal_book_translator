def test_author_byline_is_kept_verbatim() -> None:
    for line in (BYLINE_MARKERS, BYLINE_PLAIN, BYLINE_SUPER):
        reason = classify_skip(line)
        assert reason is not None and "byline" in reason, line


def test_prose_and_reference_are_not_a_byline() -> None:
    # Narrative with lowercase words / verbs fails the all-names shape.
    assert (
        classify_skip(
            "As coding agents move from supervised code completion to unattended "
            "exploration, their work expands into long trajectories."
        )
        is None
    )
    # A single name is not a byline (needs >=2).
    assert classify_skip("Mingchen Zhuge") is None
    # A real reference (year + venue + page range) is caught as a bib entry,
    # never as a byline — the year disqualifies the byline shape.
    assert classify_skip(ENTRY_FULLNAME_NEURIPS) == BIB


def test_title_case_heading_lists_are_not_bylines() -> None:
    """A heading is structure the author wrote, not somebody's name list.

    Every segment being Capitalized was enough to call it a byline, which then
    shipped the heading untranslated with MTQE_PASSED — silently, in the one
    place a reader sees it first.
    """
    for line in (
        "Purpose, Scope, and Audience",
        "Introduction, Motivation, and Outline",
        "Risk, Return, and Reward",
        "War and Peace",
    ):
        assert classify_skip(line) is None, line
    # Structure the text alone cannot express: never byline-classify a heading.
    assert classify_skip("Deep Learning and Neural Networks", is_heading=True) is None
    # The real thing still matches.
    assert classify_skip(BYLINE_PLAIN) is not None


