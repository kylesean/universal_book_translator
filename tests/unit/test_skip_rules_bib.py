# --- author byline: foreign names kept in romanization (GB/T 7714) ----------
BYLINE_MARKERS = (
    "Haozhe Liu 1* , Tian Ye 1 * , Sensen Gao 2† , Qihang Cao 2† , Yitong Li 1 † , Mingchen Zhuge"
)
BYLINE_PLAIN = "Duomin Wang 1 , Ruihua Zhang 1 , Ping Luo 1 , Lei Zhu 1 , Song Han 13"
