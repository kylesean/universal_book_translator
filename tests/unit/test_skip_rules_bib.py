def test_custom_bib_patterns_registration() -> None:
    from ubt.core.cleaners.skip_rules import register_bib_patterns, reset_custom_bib_patterns

    sample_entry = (
        "X. Wang, Y. Zhao, Neural processing architectures, Quantum Computing Review 2024."
    )
    # Before registration, "Quantum Computing Review" is not recognized as a venue
    assert classify_skip(sample_entry) is None

    try:
        register_bib_patterns(extra_venues=[r"Quantum Computing Review"])
        assert classify_skip(sample_entry) == BIB
    finally:
        reset_custom_bib_patterns()
        assert classify_skip(sample_entry) is None


def test_custom_bib_patterns_registration_is_thread_safe() -> None:
    """Concurrent registration must not lose patterns (review finding)."""
    import threading

    from ubt.core.cleaners.skip_rules import register_bib_patterns, reset_custom_bib_patterns

    sample_entry = (
        "X. Wang, Y. Zhao, Neural processing architectures, Quantum Computing Review 2024."
    )
    errors: list[BaseException] = []

    def _worker() -> None:
        try:
            register_bib_patterns(extra_venues=[r"Quantum Computing Review"])
        except BaseException as exc:  # surfaced by the assertion below
            errors.append(exc)

    threads = [threading.Thread(target=_worker) for _ in range(8)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()

    assert not errors
    try:
        assert classify_skip(sample_entry) == BIB
    finally:
        reset_custom_bib_patterns()


